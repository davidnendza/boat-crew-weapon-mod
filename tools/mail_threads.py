"""Builds src/mail_threads.h (the mail call letters, crew_mail.h) from tools/mail/threads.json.

threads.json: a list of groups {"group": ..., "threads": [{"slug", "who", "needs": [...], "sign", "steps": [...]}]}.
Run from the repo root:  python tools/mail_threads.py
Checks every thread (sender, needs, 3-5 steps, known tokens, no salutation or sign-off inside a step) and fails loudly.
"""
import json, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'mail', 'threads.json')
KEYS = os.path.join(ROOT, 'tools', 'mail', 'keys.json')     # family facts per thread: {group: {slug: [[k, v], ...]}}
KEYNAMES = {'parents', 'dadjob', 'momjob', 'home', 'brother', 'sister', 'kidbrother', 'kidsister', 'wife', 'husband', 'son', 'daughter',
            'children', 'sweetheart', 'dog', 'grandpa', 'grandma', 'dadhealth', 'room', 'church', 'house', 'sendersex',
            'underage', 'momplant', 'farmstory', 'waves', 'wedding', 'rowboat', 'flyer', 'birth', 'job', 'barber', 'ring', 'baby',
            'daughterage', 'dadwarden', 'story', 'riveter'}
OUT = os.path.join(ROOT, 'src', 'mail_threads.h')
WHO = {'mother', 'father', 'parents', 'wife', 'husband', 'sister', 'brother', 'grandmother', 'aunt', 'uncle', 'sweetheart', 'friend'}
NEEDS = {'kids', 'nokids', 'single', 'underage', 'male', 'female'}
TOKENS = {'First', 'town', 'sender', 'son', 'boy', 'brother', 'man', 'he', 'his', 'him', 'He', 'His', 'Him', 'Last'}
PIECE = 14000                                   # MSVC: a string literal piece must stay under 16380 bytes


def fail(msg):
    print('mail_threads.py: ' + msg)
    sys.exit(1)


def plain(t):
    """straight quotes and plain dashes: the game's IMGUI font, and the rest of the mod's text"""
    t = t.replace('’', "'").replace('‘', "'").replace('“', '"').replace('”', '"')
    t = t.replace('—', ' - ').replace('–', '-').replace('…', '...')
    t = re.sub(r'\s+', ' ', t).strip()
    if any(ord(c) > 126 for c in t): fail('non-ASCII text: %r' % t[:60])
    return t


def main():
    groups = json.load(open(SRC, encoding='utf-8'))
    keys = json.load(open(KEYS, encoding='utf-8')) if os.path.exists(KEYS) else {}
    sections, seen = [], set()
    for g in groups:
        for th in g['threads']:
            slug = re.sub(r'[^a-z0-9-]+', '-', th['slug'].lower()).strip('-')
            sid = 'mail.%s.%s' % (g['group'], slug)
            if sid in seen: fail('duplicate thread ' + sid)
            seen.add(sid)
            who = th['who'].strip().lower()
            if who not in WHO: fail('%s: unknown sender %r' % (sid, who))
            needs = [n.strip().lower() for n in th.get('needs', []) if n.strip()]
            for n in needs:
                if n not in NEEDS: fail('%s: unknown need %r' % (sid, n))
            steps = [plain(s) for s in th['steps']]
            if not 3 <= len(steps) <= 5: fail('%s: %d steps' % (sid, len(steps)))
            sign = plain(th['sign'])
            for text in steps + [sign]:
                for tok in re.findall(r'\{([^}]*)\}', text):
                    if tok not in TOKENS: fail('%s: unknown token {%s} in %r' % (sid, tok, text[:60]))
                if '\n' in text or '"MAIL' in text or ')MAIL' in text: fail('%s: bad characters' % sid)
            for s in steps:
                if re.match(r'(?i)dear\b', s): fail('%s: a step starts with a salutation: %r' % (sid, s[:40]))
                if re.search(r'(?i)(love,|yours,|sincerely,)\s*\S*\s*$', s): fail('%s: a step ends with a sign-off: %r' % (sid, s[-40:]))
            kv = []
            for k, v in keys.get(g['group'], {}).get(th['slug'], []):
                k = k.strip().lower(); v = plain(v).replace(',', ' ').replace(';', ' ').replace('=', ' ').replace(':', ' ').strip()
                if k.rstrip('0123456789') not in KEYNAMES: fail('%s: unknown family key %r' % (sid, k))   # dog2: a second dog
                if v and '%s:%s' % (k, v) not in kv: kv.append('%s:%s' % (k, v))
            era = int(th.get('era', 0) or 0)
            if era not in (0, 1, 2, 3): fail('%s: era %r' % (sid, era))
            lines = ['[%s]' % sid, 'who=' + who, 'needs=' + ','.join(needs), 'sign=' + sign, 'keys=' + ','.join(kv), 'era=%d' % era]
            lines += ['%d=%s' % (i + 1, s) for i, s in enumerate(steps)]
            sections.append('\n'.join(lines) + '\n')
    pieces, cur = [], ''
    for sec in sections:
        if len((cur + sec).encode('utf-8')) > PIECE: pieces.append(cur); cur = ''
        cur += '\n' + sec
    if cur: pieces.append(cur)
    out = ['// mail_threads.h: the mail call letters (crew_mail.h). GENERATED by tools/mail_threads.py from',
           '// tools/mail/threads.json; edit that and run the script. Split in pieces under MSVC\'s 16 KB string literal limit.',
           '#pragma once', 'static const char* const kMailThreads[] = {']
    for p in pieces: out.append('R"MAIL(' + p + ')MAIL",')
    out.append('};')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('mail_threads.py: %d threads, %d letters, %d piece(s) -> %s' % (len(sections), sum(s.count('\n') - 6 for s in sections), len(pieces), OUT))


if __name__ == '__main__':
    main()
