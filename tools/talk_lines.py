"""Builds src/talk_lines.h (the talking crew's lines, crew_talk.h) from tools/talk/lines.json and tools/talk/letters.json.

lines.json:   [{"name": "joker.wounded", "lines": [...]}, ...]   (voice or "any" + "." + event)
letters.json: [{"thread": "mail.mother.mother-pepper-puppies", "step": 1, "lines": [...]}, ...]
Run from the repo root:  python tools/talk_lines.py
Checks tokens, length, voices, events and that every letter section names a real thread step; fails loudly.
"""
import json, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LINES = os.path.join(ROOT, 'tools', 'talk', 'lines.json')
LETTERS = os.path.join(ROOT, 'tools', 'talk', 'letters.json')
THREADS = os.path.join(ROOT, 'tools', 'mail', 'threads.json')
OUT = os.path.join(ROOT, 'src', 'talk_lines.h')
VOICES = {'joker', 'stoic', 'crazy', 'silent', 'hothead', 'worrier', 'professional', 'cheerful', 'any'}
EVENTS = {'battle_start', 'wounded', 'kill', 'kill_plane', 'crew_down', 'crew_killed', 'crew_overboard', 'fire', 'quiet',
          'quiet_home', 'letter', 'grief', 'grief_start', 'reply_quiet', 'reply_letter', 'reply_grief', 'rollcall_here',
          'rollcall_open', 'rollcall_silence', 'rollcall_close', 'letter_returned', 'man_overboard', 'reply_letter_bad',
          'combat_gun', 'combat_ammo', 'combat_repair', 'combat_medic', 'combat_helm', 'combat_any', 'raked',
          'crew_killed_close', 'grief_close', 'grief_start_close', 'rollcall_silence_close', 'quiet_partner', 'reply_partner',
          'reply_partner_warm', 'combat_partner', 'reply_combat_partner', 'reply_combat_partner_warm', 'station_gun', 'station_job'}
ROWTAGS = {'gun', 'deadgun', 'warm', 'bad'}                              # [tag] at the start of a row (crew_talk.h)
TOKENS = {'mate', 'down', 'dead', 'deadhis', 'deadhe', 'deadplan', 'deadhome', 'deadkeep', 'home', 'plan', 'keep', 'job', 'from', 'sender', 'why'}
PIECE = 14000
MAXLEN = 90


def fail(msg):
    print('talk_lines.py: ' + msg)
    sys.exit(1)


def plain(t):
    t = t.replace('’', "'").replace('‘', "'").replace('“', '"').replace('”', '"')
    t = t.replace('—', ' - ').replace('–', '-').replace('…', '...')
    t = re.sub(r'\s+', ' ', t).strip()
    if any(ord(c) > 126 for c in t): fail('non-ASCII text: %r' % t[:60])
    return t


def check(sec, lines):
    out = []
    for l in lines:
        l = plain(l)
        if not l: continue
        for tok in re.findall(r'\{([^}]*)\}', l):
            if tok not in TOKENS: fail('%s: unknown token {%s} in %r' % (sec, tok, l))
        if len(re.sub(r'\{[^}]*\}', 'Xxxxxxxx', l)) > MAXLEN: fail('%s: too long (%d): %r' % (sec, len(l), l))
        body = l
        while body.startswith('['):
            e = body.find(']')
            if e < 0 or body[1:e] not in ROWTAGS: fail('%s: unknown row tag in %r' % (sec, l))
            body = body[e + 1:].lstrip()
        if not body or body.startswith(';') or body.startswith('#') or ')TALK' in l: fail('%s: bad start: %r' % (sec, l))
        if l not in out: out.append(l)
    return out


def main():
    threads = {}
    for g in json.load(open(THREADS, encoding='utf-8')):
        for th in g['threads']:
            slug = re.sub(r'[^a-z0-9-]+', '-', th['slug'].lower()).strip('-')
            threads['mail.%s.%s' % (g['group'], slug)] = len(th['steps'])
    sections = {}
    for s in json.load(open(LINES, encoding='utf-8')):
        name = s['name'].strip().lower()
        voice, _, event = name.partition('.')
        if voice not in VOICES or event not in EVENTS: fail('unknown section %r' % name)
        sections.setdefault(name, []).extend(check(name, s['lines']))
    missing = []
    for s in json.load(open(LETTERS, encoding='utf-8')):
        th, step = s['thread'].strip(), int(s['step'])
        if th not in threads: fail('letter lines for an unknown thread %r' % th)
        if not 1 <= step <= threads[th]: fail('%s: no step %d' % (th, step))
        name = 'letter.%s.%d' % (th, step)
        rows = check(name, s['lines'])
        if s.get('bad'): rows = ['[bad] ' + r for r in rows]          # bad news: answered with reply_letter_bad
        sections.setdefault(name, []).extend(rows)
    for th, n in threads.items():
        for st in range(1, n + 1):
            if not sections.get('letter.%s.%d' % (th, st)): missing.append('%s.%d' % (th, st))
    text = ''.join('[%s]\n%s\n\n' % (k, '\n'.join(v)) for k, v in sorted(sections.items()) if v)
    pieces, cur = [], ''
    for block in text.split('\n\n'):
        if not block.strip(): continue
        if len((cur + block).encode('utf-8')) > PIECE: pieces.append(cur); cur = ''
        cur += '\n' + block + '\n'
    if cur: pieces.append(cur)
    out = ['// talk_lines.h: the talking crew\'s lines (crew_talk.h). GENERATED by tools/talk_lines.py from tools/talk/*.json;',
           '// edit those and run the script. Split in pieces under MSVC\'s 16 KB string literal limit.',
           '#pragma once', 'static const char* const kTalkLines[] = {']
    for p in pieces: out.append('R"TALK(' + p + ')TALK",')
    out.append('};')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    n = sum(len(v) for v in sections.values())
    print('talk_lines.py: %d sections, %d lines, %d piece(s); %d letter step(s) without lines%s -> %s'
          % (len(sections), n, len(pieces), len(missing), (' (' + ', '.join(missing[:5]) + '...)') if missing else '', OUT))


if __name__ == '__main__':
    main()
