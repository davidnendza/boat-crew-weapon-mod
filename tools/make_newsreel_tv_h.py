# Rebuilds src/newsreel_tv.h from src/newsreel_tv.html (the "Newsreel TV" page the mod writes next to the GIFs).
# Run after editing the HTML: python tools/make_newsreel_tv_h.py
# MSVC caps one string literal at 16380 bytes, so the page goes in as adjacent raw literals cut at line ends.
import pathlib, re
src = pathlib.Path(__file__).resolve().parent.parent / 'src'
html = (src / 'newsreel_tv.html').read_text(encoding='utf-8')
assert ')TV"' not in html, 'raw string delimiter clash'
assert len(html.encode('utf-8')) < 60000, 'over the MSVC concatenated literal limit'
assert re.search(r'/\*FILMS\*/.*?/\*END\*/', html, re.S), 'film list markers missing'
pieces, cur = [], ''
for line in html.splitlines(keepends=True):
    if len((cur + line).encode('utf-8')) > 12000: pieces.append(cur); cur = ''
    cur += line
pieces.append(cur)
assert ''.join(pieces) == html
body = '\n'.join('R"TV(' + p + ')TV"' for p in pieces)
(src / 'newsreel_tv.h').write_text(
    '// Generated by tools/make_newsreel_tv_h.py from newsreel_tv.html; edit the HTML, not this file.\n'
    'static const char kNrTvHtml[] =\n' + body + ';\n', encoding='utf-8', newline='\r\n')
print('ok', len(html), 'bytes in', len(pieces), 'pieces')
